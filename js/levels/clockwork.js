    const H = rows * 30, n = Math.ceil(H / 80), out = [];
    for (let i = 0; i < n; i++) out.push({ t: GD.ASCII[ch].t, at, y: ((i + 0.5) * H) / n / 30 - 0.5 });
    return out;
