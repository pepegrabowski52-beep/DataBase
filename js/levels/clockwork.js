    const o = [{ t: 'sawS', at, y, g }];
    for (let r = y + 1; r <= 9; r++) o.push({ t: 'dChain', at, y: r, g });
    o.push({ t: 'tMove', at: at - lead, grp: g, dx: 0, dy: -dy, d: 0.25, e: 'inOut' });
