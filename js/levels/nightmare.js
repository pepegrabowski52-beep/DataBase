  // the wave generators only draw thin walls: fill everything above and below the channel,
  // so the wave cannot slip past a section along the ground or the top of the corridor
  const walled = (s) => {
    const g = s.split('\n').map((r) => r.split(''));
    const w = Math.max(...g.map((r) => r.length));
    for (const r of g) while (r.length < w) r.push('.');
    for (let c = 0; c < w; c++) {
      let t = 0, b = g.length - 1;
      while (t < g.length && g[t][c] === '.') t++;
      if (t === g.length) continue;
      while (g[b][c] === '.') b--;
      for (let r = 0; r < t; r++) g[r][c] = '#';
      for (let r = b + 1; r < g.length; r++) g[r][c] = '#';
    }
    return g.map((r) => r.join('')).join('\n');
  };
