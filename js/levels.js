  // Portal entered from the ground (cube / robot): low enough that it cannot be jumped over.
  const enter = (ch) => [ch, '.'].join('\n');
  // Portal leaving a flying section: a full-height wall with a 3-block opening around the portal,
  // so the portal cannot be avoided. rows = corridor height in blocks.
  const exit = (ch, row, rows) => {
    row = row == null ? 4 : row;
    rows = rows || 10;
    const a = [], b = [], c = [];
    for (let r = rows - 1; r >= 0; r--) {
      const open = r >= row - 1 && r <= row + 1;
      a.push(open ? '.' : '#');
      b.push(r === row ? ch : open ? '.' : '#');
      c.push(r === row ? 'N' : open ? '.' : '#');
    }
    return a.map((x, i) => x + b[i] + c[i]).join('\n');
  };

  // A column of identical portals covering the whole corridor without gaps (cannot be avoided).
  const stack = (ch, rows) => {
    const H = (rows || 10) * 30, n = Math.ceil(H / 80), out = [];
    for (let i = 0; i < n; i++) out.push({ t: GD.ASCII[ch].t, at: 0, y: ((i + 0.5) * H) / n / 30 - 0.5 });
    out.push(1);
    return out;
  };

  // Alternating floor / ceiling spike groups for the spider (rows = corridor height).
  const spiderAlt = (groups, gap, rows, seed) => {
    const rnd = GD.U.rng(seed || 1);
    let top = '', bot = '';
    const pad = (n) => '.'.repeat(n);
    bot += '.'; top += '.';
    let floor = true;
    for (let i = 0; i < groups; i++) {
      const n = 2 + Math.floor(rnd() * 4);
      if (floor) { bot += '^'.repeat(n); top += pad(n); } else { top += 'v'.repeat(n); bot += pad(n); }
      bot += pad(gap); top += pad(gap);
      floor = !floor;
    }
    const lines = [top];
    for (let i = 0; i < (rows || 9) - 2; i++) lines.push(pad(top.length));
    lines.push(bot);
    return lines.join('\n');
  };

